def valid(d):
    errors = []
    try:
        date.fromisoformat(d["date"])
    except ValueError:
        errors.append(f"date {d['date']}")
    if not d["session"] or len(d["session"]) > 60:
        errors.append("session")
    win = d["win"]
    if len(win) != 5 or len(set(win)) != 5 or any(not isinstance(n, int) or n < 1 or n > 90 for n in win):
        errors.append(f"win {win}")
    mach = d["machine"]
    if mach:
        if len(mach) != 5 or len(set(mach)) != 5 or any(not isinstance(n, int) or n < 1 or n > 90 for n in mach):
            errors.append(f"machine {mach}")
    return errors


def merge(parts):
    seen = {}
    order = []
    for d in parts:
        key = (d["date"], d["session"])
        if key not in seen:
            seen[key] = d
            order.append(key)
        else:
            # official site wins over capture if same key (shouldn't happen)
            seen[key] = d
    out = []
    for key in order:
        d = seen[key]
        out.append({
            "date": d["date"],
            "session": d["session"],
            "win": list(d["win"]),
            "machine": list(d["machine"]) if d["machine"] else [],
        })
    out.sort(key=lambda x: (x["date"], x["session"]))
    return out


